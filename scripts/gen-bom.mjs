// Generates the Markdown parts lists (what to get, with masses) from hardware/bom/*.json. No prices: they vary by region and supplier.
// Usage: npm run bom
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const targets = [
  { json: 'hardware/bom/monocopter.json', md: 'docs/phase1-monocopter/02-parts-list.md', phase: 'Phase 1 - MC-1 monocopter', viewer: '../../web/sizing.html?model=monocopter' },
  { json: 'hardware/bom/rocket.json', md: 'docs/phase2-rocket/02-parts-list.md', phase: 'Phase 2 - RK-1 TVC rocket', viewer: '../../web/sizing.html?model=rocket' },
];

export function totals(items) {
  const onboard = items.filter((i) => i.onboard);
  const mass = onboard.reduce((s, i) => s + i.mass_g * i.qty, 0);
  return { mass, onboardCount: onboard.length };
}

for (const t of targets) {
  const bom = JSON.parse(fs.readFileSync(path.join(root, t.json), 'utf8'));
  const { mass } = totals(bom.items);
  const cats = [...new Set(bom.items.map((i) => i.cat))];
  const out = [];
  out.push(`<!-- GENERATED by scripts/gen-bom.mjs from ${t.json}. Edit the JSON, not this file. -->`);
  out.push(`# Parts list - ${t.phase}`, '', bom.note, '');
  out.push('| Total on-board mass |', '|---|', `| **${mass.toFixed(0)} g** |`, '');
  out.push(`Live mass budget, thrust-to-weight and endurance: [${t.viewer.replace('../../', '')}](${t.viewer}).`, '');
  for (const c of cats) {
    out.push(`## ${c}`, '', '| ID | Item | Qty | Mass (g, each) | On-board | Specification / notes |', '|---|---|---:|---:|:---:|---|');
    for (const i of bom.items.filter((x) => x.cat === c)) {
      const sn = [i.spec, i.notes].filter(Boolean).join(' - ').replace(/\|/g, '/');
      out.push(`| ${i.id} | ${i.name} | ${i.qty} | ${i.mass_g} | ${i.onboard ? 'yes' : 'no'} | ${sn} |`);
    }
    out.push('');
  }
  fs.writeFileSync(path.join(root, t.md), out.join('\n'));
  console.log(`${t.phase}: ${bom.items.length} lines, on-board mass ${mass.toFixed(0)} g`);
}
