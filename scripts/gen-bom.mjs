// Generates CSV + Markdown BOM tables (with mass and cost totals) from hardware/bom/*.json.
// Usage: npm run bom
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const targets = [
  { json: 'hardware/bom/monocopter.json', csv: 'hardware/bom/monocopter.csv', md: 'docs/phase1-monocopter/02-bom.md', phase: 'Phase 1 - MC-1 monocopter', viewer: '../../web/bom.html?model=monocopter' },
  { json: 'hardware/bom/rocket.json', csv: 'hardware/bom/rocket.csv', md: 'docs/phase2-rocket/02-bom.md', phase: 'Phase 2 - RK-1 TVC rocket', viewer: '../../web/bom.html?model=rocket' },
];

export function totals(items) {
  const onboard = items.filter((i) => i.onboard);
  const mass = onboard.reduce((s, i) => s + i.mass_g * i.qty, 0);
  const cost = items.reduce((s, i) => s + i.price_usd * i.qty, 0);
  return { mass, cost, onboardCount: onboard.length };
}

const csvEsc = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;

for (const t of targets) {
  const bom = JSON.parse(fs.readFileSync(path.join(root, t.json), 'utf8'));
  const { mass, cost } = totals(bom.items);

  const header = ['id', 'category', 'name', 'qty', 'onboard', 'unit_mass_g', 'unit_price_usd', 'line_mass_g', 'line_price_usd', 'spec', 'notes'];
  const rows = bom.items.map((i) => [i.id, i.cat, i.name, i.qty, i.onboard ? 'yes' : 'no', i.mass_g, i.price_usd,
    i.onboard ? +(i.mass_g * i.qty).toFixed(1) : 0, +(i.price_usd * i.qty).toFixed(2), i.spec, i.notes]);
  fs.writeFileSync(path.join(root, t.csv), [header, ...rows].map((r) => r.map(csvEsc).join(',')).join('\n') + '\n');

  const cats = [...new Set(bom.items.map((i) => i.cat))];
  let md = `<!-- GENERATED by scripts/gen-bom.mjs from ${t.json}. Edit the JSON, not this file. -->\n`;
  md += `# Bill of materials - ${t.phase}\n\n${bom.note}\n\n`;
  md += `| Total on-board mass | Total cost (all lines, indicative) |\n|---|---|\n| **${mass.toFixed(0)} g** | **$${cost.toFixed(0)}** |\n\n`;
  md += `Interactive version with live mass budget: [${t.viewer.replace('../../', '')}](${t.viewer}). CSV: [${path.basename(t.csv)}](../../${t.csv}).\n\n`;
  for (const c of cats) {
    const items = bom.items.filter((i) => i.cat === c);
    md += `## ${c}\n\n| ID | Item | Qty | Mass (g, each) | Price ($, each) | On-board | Specification / notes |\n|---|---|---:|---:|---:|:---:|---|\n`;
    for (const i of items) {
      const sn = [i.spec, i.notes].filter(Boolean).join(' - ').replace(/\|/g, '/');
      md += `| ${i.id} | ${i.name} | ${i.qty} | ${i.mass_g} | ${i.price_usd} | ${i.onboard ? 'yes' : 'no'} | ${sn} |\n`;
    }
    md += '\n';
  }
  fs.writeFileSync(path.join(root, t.md), md);
  console.log(`${t.phase}: ${bom.items.length} lines, on-board mass ${mass.toFixed(0)} g, cost $${cost.toFixed(0)}`);
}
