// Embeds the phone app (firmware/monocopter/web/control.html) into the firmware as a C++ raw string.
//   node scripts/gen-webui.mjs          writes firmware/monocopter/include/web_ui.h
//   node scripts/gen-webui.mjs --check  fails if the header is out of date (CI)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'firmware/monocopter/web/control.html');
const dst = join(root, 'firmware/monocopter/include/web_ui.h');
const html = readFileSync(src, 'utf8').replace(/\r\n/g, '\n');
if (html.includes(')MC1HTML"')) throw new Error('control.html contains the raw-string terminator');
const out = `// GENERATED by scripts/gen-webui.mjs from firmware/monocopter/web/control.html. Edit the HTML, not this file.
#pragma once
#include <pgmspace.h>

static const char INDEX_HTML[] PROGMEM = R"MC1HTML(${html})MC1HTML";
`;
if (process.argv.includes('--check')) {
  const cur = existsSync(dst) ? readFileSync(dst, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== out) { console.error('web_ui.h is out of date; run: node scripts/gen-webui.mjs'); process.exit(1); }
  console.log('web_ui.h is current');
} else {
  writeFileSync(dst, out);
  console.log(`wrote ${dst} (${html.length} bytes of HTML)`);
}
